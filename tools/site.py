def table(heading: str, anchor: str, column: str, groups: list[dict], unit: str) -> str:
    rows = [f'<h2 id="{anchor}">{heading}</h2><table><tr><th>{column}</th><th class="n">{unit}</th>'
            f'<th class="n">Total</th><th class="n">%</th><th></th></tr>']
    for g in sorted(groups, key=lambda g: g["name"]):
        total = g["done"] + g["todo"]
        share = g["done"] / total if total else 0
        rows.append(f'<tr><td>{escape(g["name"])}</td><td class="n">{g["done"]}</td><td class="n">{total}</td>'
                    f'<td class="n">{share:.0%}</td><td>{bar(share)}</td></tr>')
    done = sum(g["done"] for g in groups)
    total = done + sum(g["todo"] for g in groups)
    rows.append(f'<tr><th>Total</th><th class="n">{done}</th><th class="n">{total}</th>'
                f'<th class="n">{done / total:.1%}</th><th></th></tr></table>')
    return "".join(rows)


