def page(title: str, here: str, body: str) -> str:
    links = [("index.html", "Home"), ("progress.html", "Progress"), ("history.html", "History"),
             (REPO, "GitHub"), (DISCORD, "Discord")]
    nav = "".join(f'<a href="{href}"{" class=here" if href == here else ""}>{name}</a>' for href, name in links)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return (f"<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            f"<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            f"<title>{escape(title)}</title><link rel=\"icon\" href=\"tengen-mark.svg\">"
            f"<style>{STYLE}</style></head><body><main><nav>{nav}</nav>\n{body}\n"
            f"<footer>Generated by <a href=\"{SOURCE}/tools/site.py\">tools/site.py</a> on every push to "
            f"<code>main</code>, {stamp}. Raw numbers: <a href=\"progress.json\">progress.json</a>. "
            f"FIRST®, FRC® and REBUILT™ are trademarks of FIRST; Tengen is an independent student project."
            f"</footer></main></body></html>\n")


def pct(value: float) -> str:
    return f"{value:.1%}"


def bar(share: float) -> str:
    return f'<span class="bar" style="width:{max(2, round(share * 80))}px"></span>'


# ----------------------------------------------------------------------------- data

def collect(models: list[dict], today: date) -> dict:
    current = next(m for m in models if m["status"] == "current")
    h = current["heldout"]
    events = []
    for label, cells in status.event_groups(h["per_frame"]):
        done = [hover.split(":")[0] for ok, hover, _ in cells if ok]
        todo = [hover.split(":")[0] for ok, hover, _ in cells if not ok]
        events.append({"name": label, "done": len(done), "todo": len(todo), "done_names": done, "todo_names": todo})
    features = []
    for category, cells in status.feature_groups():
        features.append({"name": category,
                         "done": sum(1 for ok, *_ in cells if ok), "todo": sum(1 for ok, *_ in cells if not ok),
                         "done_names": [label for ok, _, label in cells if ok],
                         "todo_names": [label for ok, _, label in cells if not ok]})
    days, model_values, feature_values = status._history(models, today)
    n = built()
    return {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "current_model": current["id"],
        "heldout": {"done": h["full_frames"], "total": h["frames"], "percent": round(100 * h["full_share"], 2),
                    "pack": load()["yardstick"]["pack"], "groups": events},
        "features": {"done": n, "total": len(FEATURES), "percent": round(100 * n / len(FEATURES), 2),
                     "groups": features},
        "models": [{k: v for k, v in m.items() if k != "heldout"} |
                   {"heldout": {k: v for k, v in (m["heldout"] or {}).items() if k != "per_frame"}}
                   for m in models],
        "history": [{"date": d.isoformat(), "model": None if mv is None else round(100 * mv, 2),
                     "features": round(100 * fv, 2)} for d, mv, fv in zip(days, model_values, feature_values)],
    }


